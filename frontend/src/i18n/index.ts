export type TranslationKey = keyof typeof translations.ru

export function useI18n() {
  const settings = useSettingsStore()

  function t(path: string, params?: Record<string, string | number>, fallback = ''): string {
    const lang = settings.language || 'ru'
    const dict = (translations as any)[lang] || translations.ru

    const parts = path.split('.')
    let current: any = dict
    for (const part of parts) {
      if (current && typeof current === 'object' && part in current) {
        current = current[part]
      } else {
        // Fallback to Russian if missing
        let fallbackCur: any = translations.ru
        for (const fbPart of parts) {
          if (fallbackCur && typeof fallbackCur === 'object' && fbPart in fallbackCur) {
            fallbackCur = fallbackCur[fbPart]
          } else {
            return fallback || path
          }
        }
        current = fallbackCur
        break
      }
    }

    if (typeof current !== 'string') {
      return fallback || path
    }

    let result = current
    if (params) {
      for (const [key, value] of Object.entries(params)) {
        result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value))
      }
    }

    return result
  }

  const currentLang = computed(() => settings.language)

  return {
    t,
    currentLang,
    locale: currentLang,
    setLanguage: settings.setLanguage,
  }
}
